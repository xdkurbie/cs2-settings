//! Write CS2 config files from Settings.
use crate::settings::{DisplayMode, Settings, TextureFilter};
use std::fs;
use std::io;
use std::path::Path;

pub fn export_all(settings: &Settings, dir: &Path) -> io::Result<Vec<String>> {
    fs::create_dir_all(dir)?;
    let mut written = Vec::new();

    let autoexec = dir.join("autoexec.cfg");
    fs::write(&autoexec, render_autoexec(settings))?;
    written.push(autoexec.display().to_string());

    let video = dir.join("cs2_video.txt");
    fs::write(&video, render_video_txt(settings))?;
    written.push(video.display().to_string());

    let binds = dir.join("binds.cfg");
    fs::write(&binds, render_binds(settings))?;
    written.push(binds.display().to_string());

    let readme = dir.join("README.txt");
    fs::write(&readme, render_readme())?;
    written.push(readme.display().to_string());

    Ok(written)
}

pub fn default_export_dir() -> std::path::PathBuf {
    dirs::document_dir()
        .unwrap_or_else(|| std::path::PathBuf::from("."))
        .join("CS2Settings-Export")
}

