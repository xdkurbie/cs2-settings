fn b01(v: bool) -> u8 {
    if v {
        1
    } else {
        0
    }
}

fn trim_f(v: f32) -> String {
    let s = format!("{:.4}", v);
    let s = s.trim_end_matches('0').trim_end_matches('.').to_string();
    if s.is_empty() || s == "-" {
        "0".into()
    } else {
        s
    }
}

