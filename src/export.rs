fn render_binds(s: &Settings) -> String {
    let mut out = String::new();
    out.push_str("// CS2 Settings — binds.cfg\n");
    out.push_str("// Exec'd from autoexec.cfg\n\n");
    for b in &s.binds {
        let key = b.key.trim();
        let cmd = b.command.trim();
        if key.is_empty() || cmd.is_empty() {
            continue;
        }
        if cmd.contains(' ') || cmd.contains(';') {
            out.push_str(&format!("bind \"{}\" \"{}\"\n", key, cmd.replace('"', "")));
        } else {
            out.push_str(&format!("bind \"{}\" {}\n", key, cmd));
        }
    }
    out
}

